// 전화번호 작대기 — 숫자만 친 번호에만, 날짜 · 계좌 같은 숫자는 그대로 (2026-10-29)
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { dashTels, telShape } from '../../../js/docs/phone.js';

test('숫자만 친 번호에 작대기', () => {
  for (const [s, want] of [['01012345678', '010-1234-5678'], ['0101234567', '010-123-4567'], ['0212345678', '02-1234-5678'],
    ['021234567', '02-123-4567'], ['03112345678', '031-1234-5678'], ['07012345678', '070-1234-5678'], ['15881234', '1588-1234']]) {
    assert.equal(dashTels(s), want, s);
  }
});

test('글자 사이의 번호도, 이미 작대기가 있으면 그대로', () => {
  assert.equal(dashTels('총무 01011112222'), '총무 010-1111-2222');
  assert.equal(dashTels('상주 01012345678 / 자녀 01098765432'), '상주 010-1234-5678 / 자녀 010-9876-5432');
  assert.equal(dashTels('총무 010-1111-2222'), '총무 010-1111-2222');
});

test('전화 모양이 아닌 숫자는 그대로', () => {
  for (const s of ['20261114', '2026-11-14', '208-09-69358', '1234567890123', '123456', '12345678']) {
    assert.equal(dashTels(s), s, s);
  }
  assert.equal(telShape('12345678'), null);
});
